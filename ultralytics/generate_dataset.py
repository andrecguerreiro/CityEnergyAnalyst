# split_and_make_yaml.py
import argparse
import random
import shutil
from pathlib import Path
import yaml

def split_dataset(root: Path, target: Path, train_frac=0.8, seed=42, force=False):
    """Split dataset from `root` into `target` (images/train, images/val, labels/train, labels/val).
    If target exists it's removed only when force=True.
    """
    random.seed(seed)

    imgs_dir = root / "images"
    labels_dir = root / "labels"

    if not imgs_dir.exists() or not imgs_dir.is_dir():
        raise FileNotFoundError(f"Images directory not found: {imgs_dir}")
    if not labels_dir.exists() or not labels_dir.is_dir():
        print(f"Warning: labels directory not found: {labels_dir} (continuing)")

    # Clean target directory if it exists and we are allowed to delete
    if target.exists():
        if not force:
            raise RuntimeError(f"Target directory {target} already exists. Re-run with --yes to overwrite.")
        print(f"Removing existing target directory: {target}")
        shutil.rmtree(target)

    # Recreate folder structure
    for sub in ("images/train", "images/val", "labels/train", "labels/val"):
        (target / sub).mkdir(parents=True, exist_ok=True)

    # collect images (support common extensions)
    imgs = sorted([p for p in imgs_dir.iterdir() if p.suffix.lower() in (".jpg", ".jpeg", ".png")])
    if not imgs:
        raise FileNotFoundError(f"No images found in {imgs_dir}")

    stems = [p.stem for p in imgs]
    random.shuffle(stems)
    n_train = int(len(stems) * train_frac)
    train_stems = stems[:n_train]
    val_stems = stems[n_train:]

    def process_label_file(src: Path, dst: Path):
        """Copy label file and append three zeros to each line."""
        if not src.exists():
            print(f"Warning: label missing for {src.stem} (copied image only)")
            return
        lines = src.read_text().strip().splitlines()
        new_lines = []
        for line in lines:
            if not line.strip():
                continue
            parts = line.strip().split()
            # append 3 zeros if not already there
            if len(parts) < 8:  # class + 4 box + 3 extras
                parts.extend(["0", "0", "0"])
            new_lines.append(" ".join(parts))
        dst.write_text("\n".join(new_lines))

    def copy_pair(stem: str, split: str):
        # find actual image file for this stem (handles mixed extensions)
        candidates = list(imgs_dir.glob(stem + ".*"))
        if not candidates:
            print(f"Warning: image not found for {stem} -- skipping")
            return
        img_src = candidates[0]
        lbl_src = labels_dir / f"{stem}.txt"

        img_dst = target / "images" / split / img_src.name
        lbl_dst = target / "labels" / split / (stem + ".txt")

        shutil.copy2(img_src, img_dst)
        process_label_file(lbl_src, lbl_dst)

    # copy files
    for s in train_stems:
        copy_pair(s, "train")
    for s in val_stems:
        copy_pair(s, "val")

    print(f"Split saved to {target} — {len(train_stems)} train, {len(val_stems)} val")
    return target

def write_yaml(target: Path, out_yaml: Path, nc=1):
    """Write dataset YAML pointing to target dataset directory."""
    cfg = {
        "path": str(target),               # IMPORTANT: dataset path should point to the new target
        "train": "images/train",
        "val": "images/val",
        "test": None,
        "nc": nc,
        "names": {0: "roof"},
        "extras": ["area", "height", "inclination"],
        "description": "Roof dataset (train/val split generated by split_and_make_yaml.py)"
    }
    out_yaml.parent.mkdir(parents=True, exist_ok=True)
    out_yaml.write_text(yaml.safe_dump(cfg))
    print(f"Wrote dataset yaml to {out_yaml}")

if __name__ == "__main__":
    parser = argparse.ArgumentParser(description="Split a flat dataset into train/val and write dataset YAML.")
    parser.add_argument("--root", default="dataset", help="Source dataset root (must contain images/ and labels/).")
    parser.add_argument("--target", default="datasets/roof_dataset", help="Target directory for split dataset.")
    parser.add_argument("--train-frac", type=float, default=0.8, help="Fraction to use for training set.")
    parser.add_argument("--out", default="datasets/roof_dataset.yaml", help="Output YAML file path.")
    parser.add_argument("--seed", type=int, default=42)
    parser.add_argument("--yes", action="store_true", help="Overwrite target directory if it exists (destructive).")
    args = parser.parse_args()

    root = Path(args.root)
    target = Path(args.target)

    # perform split
    split_dataset(root, target, train_frac=args.train_frac, seed=args.seed, force=args.yes)

    # write yaml pointing to target dir
    write_yaml(target, Path(args.out))